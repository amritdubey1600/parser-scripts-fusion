fab.ATTRIBUTE4 as HEADER_BUDGET,
TO_CHAR(fab.ATTRIBUTE_DATE1,'MM/DD/YYYY') as  ECD,
fai.ATTRIBUTE_NUMBER1 AS ACCOUNT_ES_COA,
fai.DESCRIPTION AS LINE_DESCRIPTION,
fai.FIXED_ASSETS_COST AS FUNCTIONAL_CURRENCY_AMOUNT,
 (select (FMAI.FIXED_ASSETS_COST)
 From FA_MC_ASSET_INVOICES FMAI
 where FMAI.SOURCE_LINE_ID = FAI.SOURCE_LINE_ID ) as TRANSACTIONAL_CURRENCY_AMOUNT,
TO_CHAR(fai.ATTRIBUTE_DATE1,'MM/DD/YYYY') AS ENTRY_DATE,  
fai.ATTRIBUTE9 as Year,
fai.ATTRIBUTE8 AS PERIOD,
fai.ATTRIBUTE1 as TRANSACTIONAL_CURRENCY,
fai.ATTRIBUTE2 AS JE_REFERENCE,
fai.ATTRIBUTE3 AS JE_SOURCE,
fai.ATTRIBUTE_NUMBER3 AS JE_JOURNAL_NUMBER,
TO_CHAR(fai.ATTRIBUTE_DATE2,'MM/DD/YYYY') AS INVOICE_DATE,
fai.ATTRIBUTE4 as INVOICE_NUMBER,
fai.ATTRIBUTE5 AS VENDOR_NUMBER,
fai.ATTRIBUTE6 AS VENDOR_NAME,
fab.ATTRIBUTE2 AS EQUIPMENT_NUMBER,
fai.ATTRIBUTE7 AS PO_NUMBER,
gcc.segment1 AS COMPANY,
FAI.SOURCE_LINE_ID,
NULL as PERCENT_BUDGET,
TO_CHAR(FAI.DATE_INEFFECTIVE,'MM/DD/YYYY') as Transfer_date,
(select  distinct fab2.asset_number
from FA_ASSET_INVOICES fai2
    ,FA_ADDITIONS_B FAB2 
where FAB2.Asset_id = FAI2.ASSET_ID
and  fai2.invoice_Transaction_id_in = fai.invoice_Transaction_id_out
and fai2.invoice_Transaction_id_out is null
and fai2.DATE_INEFFECTIVE is NULL
and fai2.PRIOR_SOURCE_LINE_ID = fai.SOURCE_LINE_ID
and fai2.Asset_ID ! = fai.asset_id 
) as Transfer_Asset_number, 
 (CASE WHEN FAB.ATTRIBUTE_DATE1 IS NULL THEN ' '
       WHEN ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30) > 12 THEN 'GREATER THAN 12 MONTHS'
       WHEN ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30) > 9 AND ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30) <= 12  THEN 'LESS THAN 12 MONTHS'
       WHEN ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30) > 6 AND ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30) <= 9  THEN 'LESS THAN 9 MONTHS'
       WHEN ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30) > 3 AND ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30) <= 6  THEN 'LESS THAN 6 MONTHS'
       WHEN ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30) > 0 AND ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30) <= 3  THEN 'LESS THAN 3 MONTHS' 
       when  ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30)= 0 THEN 'NA'
       WHEN ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30) < 0 AND ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30) >= -3 THEN 'NA'
       WHEN ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30) < -3  AND ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30)>= -6 THEN 'NA'
       WHEN ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30) < -6 AND ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30)>= -9 THEN 'NA'
       WHEN ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30) < -9 AND ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30)>= -12 THEN 'NA'
       WHEN ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30) < -12 AND ((SYSDATE-FAB.ATTRIBUTE_DATE1)/30)>= -60 THEN 'NA'
else 'CANNOT CALCULATE'  END) AS Percent_ECD,
TO_CHAR(fai.CREATION_DATE,'MM/DD/YYYY') AS CREATION_DATE1,
TO_CHAR(fab.creation_date,'MM/DD/YYYY') AS creation_date2 --Added  REL-012 , Case#17099498
FROM FA_BOOKS A,
     FA_ADDITIONS_B  fab,
     FA_ASSET_INVOICES fai
    ,FA_DISTRIBUTION_HISTORY fdh
    ,GL_CODE_COMBINATIONS gcc
where 1=1 
  AND A.ASSET_ID = FAB.ASSET_ID 
  AND a.transaction_header_id_out IS NULL
  AND a.date_ineffective IS NULL 
  AND fai.ASSET_ID = fab.ASSET_ID
  and fdh.ASSET_ID = fab.ASSET_ID
  AND FDH.transaction_header_id_out IS NULL
  AND FDH.date_ineffective IS NULL
  AND FAI.DATE_INEFFECTIVE is not NULL -- Added
  AND FAI.INVOICE_TRANSACTION_ID_OUT is not Null -- Added
  AND FAI.INVOICE_TRANSACTION_ID_OUT in (select INVOICE_TRANSACTION_ID from FA_INVOICE_TRANSACTIONS where TRANSACTION_TYPE = 'INVOICE TRANSFER')
  and gcc.CODE_COMBINATION_ID = fdh.CODE_COMBINATION_ID
  and decode(fab.ATTRIBUTE1,NULL,'a',fab.ATTRIBUTE1) =nvl(:PAR_Number,decode(fab.ATTRIBUTE1,NULL,'a',fab.ATTRIBUTE1))
  and gcc.segment1 =  NVL(:Company_code,gcc.segment1)
  AND to_date(A.DATE_PLACED_IN_SERVICE)<=(SELECT calendar_period_close_date
                                FROM FA_DEPRN_PERIODS
                                WHERE period_name = :P_ACC_PERIOD
                                AND book_type_code ='CA_CAD_CORP')
  and fab.ASSET_TYPE = 'CIP'
