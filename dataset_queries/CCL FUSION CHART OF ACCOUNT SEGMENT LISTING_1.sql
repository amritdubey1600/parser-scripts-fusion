SELECT  t.flex_value,t.description,DECODE(SUBSTR( T.compiled_value_attributes, 7, 1 ),'A','Asset','L','Liability','E','Expense','O','Owners Equity','R','Revenue',NULL)      Account_type,t.SUMMARY_FLAG,t.ENABLED_FLAG,t.START_DATE_ACTIVE,t.END_DATE_ACTIVE 
FROM FND_ID_FLEX_STRUCTURES_VL FS,FND_ID_FLEX_SEGMENTS_VL FSS,FND_FLEX_VALUES_VL T
WHERE FS.ID_FLEX_STRUCTURE_CODE='CCL Accounting Flexfield'
AND FSS.FORM_LEFT_PROMPT=:P_CC_CODE
AND T.ENABLED_FLAG=DECODE(:P_ACTIVE,'Y','Y',T.ENABLED_FLAG)
AND FSS.ID_FLEX_CODE=FS.ID_FLEX_CODE
AND FSS.APPLICATION_ID=FS.APPLICATION_ID
AND FSS.ID_FLEX_NUM=FS.ID_FLEX_NUM
AND FSS.FLEX_VALUE_SET_ID=T.FLEX_VALUE_SET_ID
ORDER BY FSS.SEGMENT_NUM