SELECT DH.ASSET_ID ASSET_ID_DIST,
       DH.BOOK_TYPE_CODE BOOK_TYPE_CODE_DIST,
       &d_gl_account D_GL_ACCOUNT1,
       &d_location D_LOCATION1,
       EMP.PERSON_NUMBER EMPLOYEE_NUMBER,
       EMP.PERSON_ID EMPLOYEE_NAME,
       DH.UNITS_ASSIGNED UNITS,
       CC.SEGMENT1 COMPANY_CODE,
       TO_CHAR(CC.SEGMENT4) COST_CENTER,
       LOC.SEGMENT1 COUNTRY,
       LOC.SEGMENT2 STATE,
       LOC.SEGMENT3 CITY,
       LOC.SEGMENT4 BUILDING,
       LOC.SEGMENT5 BUILDING_ID
  FROM FA_LOCATIONS LOC,
       GL_CODE_COMBINATIONS CC,
       PER_ALL_PEOPLE_F EMP,
       FA_DISTRIBUTION_HISTORY DH,
       FA_BOOK_CONTROLS BC
 WHERE     DH.CODE_COMBINATION_ID = CC.CODE_COMBINATION_ID
       AND DH.ASSIGNED_TO IS NOT NULL
       AND DH.ASSIGNED_TO = EMP.PERSON_ID
       AND TRUNC (DH.DATE_EFFECTIVE) BETWEEN EMP.EFFECTIVE_START_DATE
                                         AND EMP.EFFECTIVE_END_DATE
       AND DH.LOCATION_ID = LOC.LOCATION_ID
       AND DH.DATE_INEFFECTIVE IS NULL
       AND DH.BOOK_TYPE_CODE = BC.BOOK_TYPE_CODE
       AND BC.BOOK_TYPE_CODE = UPPER (:P_BOOK)
       AND DH.ASSET_ID = :ASSET_ID_MASTER
UNION ALL
