SELECT  FSS.FORM_LEFT_PROMPT
from FND_ID_FLEX_STRUCTURES_VL FS,FND_ID_FLEX_SEGMENTS_VL FSS
where 1=1
AND FSS.ID_FLEX_CODE=FS.ID_FLEX_CODE
and FS.ID_FLEX_STRUCTURE_CODE='CCL Accounting Flexfield'
AND FSS.APPLICATION_ID=FS.APPLICATION_ID
AND FSS.ID_FLEX_NUM=FS.ID_FLEX_NUM
ORDER BY FSS.SEGMENT_NUM