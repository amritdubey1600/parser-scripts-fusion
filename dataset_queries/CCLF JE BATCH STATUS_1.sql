Select
JB.NAME BATCH_NAME,
JB.DEFAULT_PERIOD_NAME PERIOD,
JB.CREATION_DATE,
JS.DESCRIPTION SOURCE,
JB.RUNNING_TOTAL_DR,
JB.RUNNING_TOTAL_CR,
L.DESCRIPTION ERROR,
LG.NAME LEDGER_NAME
from 
gl_je_batches JB, 
GL_LOOKUPS L,
GL_JE_HEADERS JH,
GL_LEDGERS LG,
GL_JE_SOURCES_TL JS
where JB.STATUS = L.LOOKUP_CODE
AND JB.JE_BATCH_ID = JH.JE_BATCH_ID
AND JH.LEDGER_ID = LG.LEDGER_ID
AND JH.JE_SOURCE = JS.JE_SOURCE_NAME
AND JB.STATUS NOT IN ('P','U')
AND JS.LANGUAGE = 'US'
AND L.LOOKUP_TYPE = 'MJE_BATCH_STATUS' 
AND JB.DEFAULT_PERIOD_NAME =  :P_PERIOD
--AND JB.NAME ='Spreadsheet A 300000004391592 243523 N'