SELECT AI.ASSET_ID ASSET_ID_INV,
       AI.INVOICE_NUMBER,
       AI.INVOICE_LINE_NUMBER || ' - ' || AI.AP_DISTRIBUTION_LINE_NUMBER
          AP_DISTRIBUTION_LINE_NUMBER,
       AI.DESCRIPTION DESCRIPTION2,
       PO.SEGMENT1 SEGMENT1,
       PO.VENDOR_NAME,
       AI.PO_NUMBER,
       PO.SEGMENT1 VENDOR_NUMBER,
       PPA.SEGMENT1 PROJECT_NUMBER
  FROM &L_INVOICES AI, POZ_SUPPLIERS_V PO, PJF_PROJECTS_ALL_B PPA
 WHERE AI.PO_VENDOR_ID = PO.VENDOR_ID(+) AND &L_SOB_INV
       AI.DATE_INEFFECTIVE IS NULL
 AND AI.PROJECT_ID = PPA.PROJECT_ID(+)
 and AI.ASSET_ID=:ASSET_ID_MASTER
ORDER BY 1,2,3