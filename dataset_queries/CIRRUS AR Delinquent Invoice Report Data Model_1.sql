SELECT LGR.NAME "LEDGER_NAME",
  HOU.NAME "BUSINESS UNIT",
  (SELECT HCA.ACCOUNT_NUMBER
  FROM HZ_PARTIES HP,
    HZ_CUST_ACCOUNTS HCA
  WHERE HP.PARTY_ID   = HCA.PARTY_ID
  AND APS.CUSTOMER_ID = HCA.CUST_ACCOUNT_ID
  AND APS.CUSTOMER_ID = HCA1.CUST_ACCOUNT_ID
  ) CUSTOMER_NUMBER,
  (SELECT HP.PARTY_NAME
  FROM HZ_PARTIES HP,
    HZ_CUST_ACCOUNTS HCA
  WHERE HP.PARTY_ID   = HCA.PARTY_ID
  AND APS.CUSTOMER_ID = HCA.CUST_ACCOUNT_ID
  AND APS.CUSTOMER_ID = HCA1.CUST_ACCOUNT_ID
  ) CUSTOMER_NAME,
  (SELECT HPS.PARTY_SITE_NAME
  FROM HZ_PARTIES HP,
  HZ_PARTY_SITES HPS,
  HZ_CUST_SITE_USES_All HCSUA,
  HZ_CUST_ACCT_SITES_ALL HCASA
  WHERE HP.PARTY_ID   = HCA1.PARTY_ID
  AND APS.CUSTOMER_ID = HCA1.CUST_ACCOUNT_ID
  AND HCSUA.SITE_USE_CODE = 'BILL_TO'
  AND RCT.BILL_TO_SITE_USE_ID = HCSUA.SITE_USE_ID
  AND HCSUA.CUST_ACCT_SITE_ID=HCASA.CUST_ACCT_SITE_ID
  AND HCASA.PARTY_SITE_ID = HPS.PARTY_SITE_ID
  AND HP.PARTY_ID = HPS.PARTY_ID
  )  "BILL_TO_SITE_NAME",
  decode(RCT.ATTRIBUTE1,'Y','Yes','N','No') "DISPUTED_INVOICES",
  RCT.TRX_NUMBER "INVOICE NUMBER",
  TO_CHAR(RCT.TRX_DATE, 'MM-DD-YYYY') "INVOICE DATE",
  RCT.INVOICE_CURRENCY_CODE "INVOICE_CURRENCY_CODE",
  RTH.NAME "PAYMENT TERM",
  TO_CHAR(APS.DUE_DATE, 'MM-DD-YYYY') "PMT DUE DATE",
  APS.AMOUNT_DUE_ORIGINAL "INVOICE AMOUNT",
  APS.AMOUNT_DUE_REMAINING "AMOUNT_PAST_DUE",
 (SELECT TO_DATE(TO_CHAR(:TRX_AS_OF_DATE_IN_MM_DD_YY, 'MM-DD-YY'),'MM-DD-YY') - TO_DATE(TO_CHAR(APS.DUE_DATE,'MM-DD-YY'),'MM-DD-YY')
     FROM DUAL) "DELINQUENT_DAYS"
FROM RA_CUSTOMER_TRX_ALL RCT,
  AR_PAYMENT_SCHEDULES_ALL APS,
  RA_TERMS_VL RTH,
  HZ_CUST_ACCOUNTS HCA1,
  HR_OPERATING_UNITS HOU, 
  GL_LEDGERS LGR
WHERE 1                       =1
AND APS.CUSTOMER_TRX_ID       = RCT.CUSTOMER_TRX_ID
AND APS.TERM_ID               = RTH.TERM_ID
AND APS.ORG_ID                = HOU.ORGANIZATION_ID
AND LGR.LEDGER_ID             = HOU.SET_OF_BOOKS_ID
AND APS.CUSTOMER_ID = HCA1.CUST_ACCOUNT_ID
AND HCA1.CUSTOMER_TYPE = 'R'
AND APS.AMOUNT_DUE_REMAINING <> 0
AND RCT.COMPLETE_FLAG         = 'Y'
AND APS.CLASS = 'INV'
AND RCT.ATTRIBUTE_CATEGORY = 'Cirrus Invoice Header'  
AND RCT.CUSTOMER_TRX_ID = (SELECT DISTINCT A.CUSTOMER_TRX_ID
							FROM RA_CUSTOMER_TRX_ALL A,RA_CUSTOMER_TRX_LINES_ALL B,
							EGP_SYSTEM_ITEMS_B C
							WHERE 
							RCT.CUSTOMER_TRX_ID =A.CUSTOMER_TRX_ID
							AND A.CUSTOMER_TRX_ID =B.CUSTOMER_TRX_ID
							AND B.INVENTORY_ITEM_ID = C.INVENTORY_ITEM_ID
							AND B.INVENTORY_ITEM_ID IS NOT NULL
							AND B.WAREHOUSE_ID = C.ORGANIZATION_ID
							AND C.ATTRIBUTE_CATEGORY = 'GED Context'
							----AND C.ATTRIBUTE23 IS NOT NULL
							AND C.ATTRIBUTE23  = NVL(:FULFILMENT_SYSTEM_ATTRIBUTE,C.ATTRIBUTE23)) 
AND LGR.NAME                                                                  =NVL(:LEDGER_NAME,LGR.NAME)
AND HOU.NAME                                                                  =NVL(:BUSINESS_UNIT,HOU.NAME)
AND TO_DATE(TO_CHAR(:TRX_AS_OF_DATE_IN_MM_DD_YY, 'MM-DD-YY'),'MM-DD-YY') - TO_DATE(TO_CHAR(APS.DUE_DATE,'MM-DD-YY'),'MM-DD-YY') >60

UNION 

SELECT LGR.NAME "LEDGER_NAME",
  HOU.NAME "BUSINESS UNIT",
  (SELECT HCA.ACCOUNT_NUMBER
  FROM HZ_PARTIES HP,
    HZ_CUST_ACCOUNTS HCA
  WHERE HP.PARTY_ID   = HCA.PARTY_ID
  AND APS.CUSTOMER_ID = HCA.CUST_ACCOUNT_ID
  AND APS.CUSTOMER_ID = HCA1.CUST_ACCOUNT_ID
  ) CUSTOMER_NUMBER,
  (SELECT HP.PARTY_NAME
  FROM HZ_PARTIES HP,
    HZ_CUST_ACCOUNTS HCA
  WHERE HP.PARTY_ID   = HCA.PARTY_ID
  AND APS.CUSTOMER_ID = HCA.CUST_ACCOUNT_ID
  AND APS.CUSTOMER_ID = HCA1.CUST_ACCOUNT_ID
  ) CUSTOMER_NAME,
  (SELECT HPS.PARTY_SITE_NAME
  FROM HZ_PARTIES HP,
  HZ_PARTY_SITES HPS,
  HZ_CUST_SITE_USES_All HCSUA,
  HZ_CUST_ACCT_SITES_ALL HCASA
  WHERE HP.PARTY_ID   = HCA1.PARTY_ID
  AND APS.CUSTOMER_ID = HCA1.CUST_ACCOUNT_ID
  AND HCSUA.SITE_USE_CODE = 'BILL_TO'
  AND RCT.BILL_TO_SITE_USE_ID = HCSUA.SITE_USE_ID
  AND HCSUA.CUST_ACCT_SITE_ID=HCASA.CUST_ACCT_SITE_ID
  AND HCASA.PARTY_SITE_ID = HPS.PARTY_SITE_ID
  AND HP.PARTY_ID = HPS.PARTY_ID
  )  "BILL_TO_SITE_NAME",
  NULL "DISPUTED_INVOICES",
  RCT.TRX_NUMBER "INVOICE NUMBER",
  TO_CHAR(RCT.TRX_DATE, 'MM-DD-YYYY') "INVOICE DATE",
  RCT.INVOICE_CURRENCY_CODE "INVOICE_CURRENCY_CODE",
  RTH.NAME "PAYMENT TERM",
  TO_CHAR(APS.DUE_DATE, 'MM-DD-YYYY') "PMT DUE DATE",
  APS.AMOUNT_DUE_ORIGINAL "INVOICE AMOUNT",
  APS.AMOUNT_DUE_REMAINING "AMOUNT_PAST_DUE",
 (SELECT TO_DATE(TO_CHAR(:TRX_AS_OF_DATE_IN_MM_DD_YY, 'MM-DD-YY'),'MM-DD-YY') - TO_DATE(TO_CHAR(APS.DUE_DATE,'MM-DD-YY'),'MM-DD-YY')
      FROM DUAL) "DELINQUENT_DAYS"
FROM RA_CUSTOMER_TRX_ALL RCT,
  AR_PAYMENT_SCHEDULES_ALL APS,
  RA_TERMS_VL RTH,
  HZ_CUST_ACCOUNTS HCA1,
  HR_OPERATING_UNITS HOU, 
  GL_LEDGERS LGR
WHERE 1                       =1
AND APS.CUSTOMER_TRX_ID       = RCT.CUSTOMER_TRX_ID
AND APS.TERM_ID               = RTH.TERM_ID
AND APS.ORG_ID                = HOU.ORGANIZATION_ID
AND LGR.LEDGER_ID             = HOU.SET_OF_BOOKS_ID
AND APS.CUSTOMER_ID = HCA1.CUST_ACCOUNT_ID
AND HCA1.CUSTOMER_TYPE = 'R'
AND APS.AMOUNT_DUE_REMAINING <> 0
AND RCT.COMPLETE_FLAG         = 'Y'
AND APS.CLASS = 'INV'
AND (RCT.ATTRIBUTE_CATEGORY is null or RCT.ATTRIBUTE_CATEGORY <> 'Cirrus Invoice Header')  
AND RCT.CUSTOMER_TRX_ID = (SELECT DISTINCT B.CUSTOMER_TRX_ID
							FROM 
							RA_CUSTOMER_TRX_ALL A,
							RA_CUSTOMER_TRX_LINES_ALL B,
							EGP_SYSTEM_ITEMS_B C
							WHERE 
							RCT.CUSTOMER_TRX_ID =B.CUSTOMER_TRX_ID
							AND A.CUSTOMER_TRX_ID =B.CUSTOMER_TRX_ID
							AND B.INVENTORY_ITEM_ID = C.INVENTORY_ITEM_ID
							AND B.INVENTORY_ITEM_ID IS NOT NULL
							AND B.WAREHOUSE_ID = C.ORGANIZATION_ID
							AND C.ATTRIBUTE_CATEGORY = 'GED Context'
							---AND C.ATTRIBUTE23 IS NOT NULL
							AND C.ATTRIBUTE23  = NVL(:FULFILMENT_SYSTEM_ATTRIBUTE,C.ATTRIBUTE23)) 
AND LGR.NAME                                                                  =NVL(:LEDGER_NAME,LGR.NAME)
AND HOU.NAME                                                                  =NVL(:BUSINESS_UNIT,HOU.NAME)
AND TO_DATE(TO_CHAR(:TRX_AS_OF_DATE_IN_MM_DD_YY, 'MM-DD-YY'),'MM-DD-YY') - TO_DATE(TO_CHAR(APS.DUE_DATE,'MM-DD-YY'),'MM-DD-YY') >60
--ORDER BY LGR.NAME,   HOU.NAME,  HCA1.ACCOUNT_NUMBER, RCT.CUSTOMER_TRX_ID DESC
ORDER BY 1,2,3,4 DESC