SELECT DISTINCT
L.NAME PRIMARY_LEDGER,
LR.TARGET_LEDGER_NAME STAT_LEDGER,
LR.TARGET_CURRENCY_CODE STAT_LEDGER_CURR,
--LR.PRIMARY_LEDGER_ID,
R.INCLUDE_FLAG INCLUDE,
LR.TARGET_LEDGER_CATEGORY_CODE LEDGER_TYPE,
LR.RELATIONSHIP_TYPE_CODE CONV_TYPE,
C.USER_JE_CATEGORY_NAME JE_CATEGORY,
S.USER_JE_SOURCE_NAME JE_SOURCE 
FROM
GL_LEDGER_RELATIONSHIPS LR,
GL_JE_INCLUSION_RULES R,
GL_JE_CATEGORIES_TL C,
GL_JE_SOURCES_TL S,
GL_LEDGERS L
WHERE 
L.LEDGER_ID = LR.PRIMARY_LEDGER_ID
AND LR.GL_JE_CONVERSION_SET_ID = R.JE_RULE_SET_ID
AND C.JE_CATEGORY_NAME  = R.JE_CATEGORY_NAME
AND C.LANGUAGE = 'US' 
AND S.JE_SOURCE_NAME = R.JE_SOURCE_NAME
AND S.LANGUAGE = 'US'
AND LR.GL_JE_CONVERSION_SET_ID IS NOT NULL
--AND LR.TARGET_LEDGER_CATEGORY_CODE <> 'SECONDARY'
AND LENGTH(LR.TARGET_LEDGER_NAME) = 10
ORDER BY LR.TARGET_LEDGER_NAME
--AND LR.TARGET_LEDGER_NAME = 'CA_CAD_STA'
	
